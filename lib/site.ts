/**
 * Builds an openGraph metadata block for a child page.
 *
 * Next.js does NOT deep-merge `openGraph` from the root layout: a page that
 * declares its own og:title silently drops the inherited og:image, and the page
 * ends up sharing as a blank card. This helper re-attaches the default image (and
 * the site-level constants) so each page only has to supply what is actually
 * page-specific.
 */
export function pageOpenGraph({
  path,
  title,
  description,
  type = 'website',
  images,
}: {
  path: string;
  title: string;
  description: string;
  type?: 'website' | 'article';
  images?: { url: string; alt?: string }[];
}) {
  return {
    type,
    url: path,
    siteName: SITE.name,
    locale: SITE.locale,
    title,
    description,
    images: images ?? [
      { url: SITE.ogImage, width: 1200, height: 630, alt: 'Argostep maritim leider' },
    ],
  } as const;
}
