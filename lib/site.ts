/**
 * Single source of truth for everything that describes the site to the outside
 * world: search engines, AI answer engines, social crawlers and JSON-LD.
 *
 * Every metadata export and every structured-data block reads from here, so a
 * change to the phone number or the address propagates everywhere at once
 * instead of drifting between the footer, the schema and the OG tags. Entity
 * consistency (same name, same NAP, same identifiers everywhere) is the single
 * biggest lever for how confidently Google and LLM-based search surface a
 * small brand.
 */

/**
 * Canonical origin, no trailing slash.
 *
 * Order of precedence:
 *  1. NEXT_PUBLIC_SITE_URL – set this in Vercel for full control.
 *  2. VERCEL_PROJECT_PRODUCTION_URL – the production domain Vercel knows about,
 *     so preview deploys still emit production canonicals instead of pointing
 *     search engines at a preview URL.
 *  3. The live domain, hard-coded as a last resort.
 */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL ||
  (process.env.VERCEL_PROJECT_PRODUCTION_URL
    ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
    : 'https://northwestcoast.no')
).replace(/\/$/, '');

/** Absolute URL for a site-relative path. Structured data must never use relative URLs. */
